#!/usr/bin/env bash
# bench-harness × vireon.conf matrix v2 — fresh server per mode.
#
# Restarts the server (or cluster) before each bench mode to avoid
# zombie connections from prior modes diluting reactor throughput.
#
# Modes exercised per variant:
#   stream     — 1 conn, full-duplex throughput
#   rr         — 1 conn, request-response (legacy / RPC path)
#   broadcast  — 4 conns (1 pub + 3 sub), fan-out delivery
#   group      — 4 conns (1 pub + 3 members), consumer-group round-robin
#
# PASS criteria: exit code 0 AND (for broadcast/group) duplicates == 0.
#
# Runtime workspace (logs, generated cluster/migration confs) stays at
# /tmp/vireon-conf-test; certs are read from the repo root so the
# scripts/ directory is self-contained.
set -u

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
SRV=$ROOT/target/x86_64-unknown-linux-gnu/release/quic-server
LOADTEST=$ROOT/target/x86_64-unknown-linux-gnu/release/loadtest
CERT=$ROOT/cert.pem
KEY=$ROOT/key.pem
CONF_DIR=/tmp/vireon-conf-test
RUN_ID=$$

# Kill any lingering server processes to avoid ghost-socket interference.
# Match the binary path specifically so we don't kill our own shell.
pkill -f "$SRV" 2>/dev/null
sleep 3

cd "$ROOT" || exit 1

mkdir -p "$CONF_DIR"

# Sanity: certs must exist.
if [ ! -f "$CERT" ] || [ ! -f "$KEY" ]; then
    echo "ERROR: dev certs missing — expected $CERT and $KEY" >&2
    exit 1
fi

# Auto-generate the base single.conf / multi.conf so the script is
# self-contained (no checked-in conf files needed).
write_base_confs() {
    cat > "$CONF_DIR/single.conf" <<EOF
# Auto-generated by scripts/run-bench-matrix.sh (run_id=$RUN_ID).
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "single"
workers = 1
skip_crc = true
log_format = "text"
metrics_port = 0

[wal_sync]
mode = "never"
EOF
    cat > "$CONF_DIR/multi.conf" <<EOF
# Auto-generated by scripts/run-bench-matrix.sh (run_id=$RUN_ID).
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "multi"
workers = 4
skip_crc = true
log_format = "text"
metrics_port = 0

[wal_sync]
mode = "never"
EOF
}
write_base_confs

SINGLE_MODES=(broadcast group stream rr)
MULTI_MODES=(broadcast group stream rr)

RESULTS=()

free_port() {
    python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1",0)); print(s.getsockname()[1]); s.close()'
}

free_port_clean() {
    for _ in $(seq 1 50); do
        local p
        p=$(free_port)
        if ! ss -uln 2>/dev/null | grep -q ":$p "; then
            echo "$p"
            return 0
        fi
    done
    echo "ERROR: no clean port found after 50 tries" >&2
    return 1
}

wait_ready() {
    local port=$1
    for _ in $(seq 1 75); do
        if ss -uln 2>/dev/null | grep -q ":$port "; then
            return 0
        fi
        sleep 0.2
    done
    return 1
}

start_server() {
    local conf=$1 port=$2
    $SRV --config "$conf" --port "$port" > "$CONF_DIR/srv-$RUN_ID-$port.log" 2>&1 &
    local pid=$!
    if ! wait_ready "$port"; then
        echo "FAIL: server didn't bind $port" >&2
        return 1
    fi
    echo "$pid"
}

stop_pid() {
    local pid=$1
    kill -INT "$pid" 2>/dev/null
    for _ in $(seq 1 50); do
        kill -0 "$pid" 2>/dev/null || return 0
        sleep 0.1
    done
    kill -9 "$pid" 2>/dev/null
}

extract_metric() {
    local log=$1 mode=$2 dur=$3
    case "$mode" in
        stream|rr|multi-rr|pipeline)
            local fps mib mibs
            fps=$(grep -oP '^frames/sec:\s+\K[0-9.]+' "$log" 2>/dev/null | head -1)
            mib=$(grep -oP '^bytes:\s+\K[0-9.]+' "$log" 2>/dev/null | head -1)
            if [ -n "$fps" ]; then
                if [ -n "$mib" ] && [ -n "$dur" ]; then
                    mibs=$(awk "BEGIN{printf \"%.0f\", $mib/$dur}")
                    echo "${fps} fps | ${mibs} MiB/s"
                else
                    echo "${fps} fps"
                fi
            fi
            ;;
        broadcast)
            local fan dup tx rx
            fan=$(grep -oP 'fanout multiplier\s+\K[0-9.]+x' "$log" 2>/dev/null | head -1)
            dup=$(grep -oP '^  duplicates\s+\K[0-9]+' "$log" 2>/dev/null | head -1)
            tx=$(grep -oP '^throughput:\s+\K[0-9.]+' "$log" 2>/dev/null | head -1)
            rx=$(grep -oP 'RX MiB/s\s+\K[0-9.]+' "$log" 2>/dev/null | head -1)
            echo "pub ${tx:-?} MiB/s | recv ${rx:-?} MiB/s | fanout ${fan:-?} | dup=${dup:-0}"
            ;;
        group)
            local dup tx rx
            dup=$(grep -oP '^  duplicates\s+\K[0-9]+' "$log" 2>/dev/null | head -1)
            tx=$(grep -oP '^throughput:\s+\K[0-9.]+' "$log" 2>/dev/null | head -1)
            rx=$(grep -oP 'RX MiB/s\s+\K[0-9.]+' "$log" 2>/dev/null | head -1)
            echo "pub ${tx:-?} MiB/s | recv ${rx:-?} MiB/s | dup=${dup:-0}"
            ;;
    esac
}

run_mode() {
    local variant=$1 mode=$2 addr=$3 conns=$4 dur=$5
    local log="$CONF_DIR/bench-${RUN_ID}-${variant}-${mode}-${conns}.log"
    local start=$(date +%s.%N)
    $LOADTEST --target "$addr" --mode "$mode" --conns "$conns" --duration "$dur" \
        > "$log" 2>&1
    local rc=$?
    local end=$(date +%s.%N)
    local elapsed=$(awk "BEGIN{printf \"%.1f\", $end-$start}")
    local metric=$(extract_metric "$log" "$mode" "$dur")

    if [ $rc -ne 0 ]; then
        echo "FAIL(rc=$rc) ${elapsed}s"
        return
    fi
    if [[ "$mode" == "broadcast" || "$mode" == "group" ]]; then
        local dups=$(grep -E "^  duplicates +[0-9]+" "$log" | awk '{print $2}')
        dups=${dups:-0}
        if [ "$dups" -ne 0 ]; then
            echo "FAIL(dup=$dups) ${elapsed}s | ${metric}"
            return
        fi
    fi
    echo "PASS ${elapsed}s | ${metric}"
}

conns_for_mode() {
    case "$1" in
        stream|rr) echo 1;;
        broadcast|group) echo 4;;
    esac
}

# ── Per-mode runner helpers (fresh server each time) ─────────────

run_single_mode() {
    local variant=$1 conf=$2 mode=$3
    local conns; conns=$(conns_for_mode "$mode")
    local port; port=$(free_port_clean)
    local pid; pid=$(start_server "$conf" "$port")
    if [ -z "$pid" ]; then
        printf "  %-14s conns=%-2d  %s\n" "$mode" "$conns" "FAIL(server)"
        RESULTS+=("$variant|$mode|FAIL(server)")
        return
    fi
    local res; res=$(run_mode "$variant" "$mode" "127.0.0.1:$port" "$conns" 5)
    printf "  %-14s conns=%-2d  %s\n" "$mode" "$conns" "$res"
    RESULTS+=("$variant|$mode|$res")
    stop_pid "$pid"
    sleep 1
}

write_cluster_conf() {
    local file=$1 mode=$2 workers=$3 peers=$4
    cat > "$file" <<EOF
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "$mode"
workers = $workers
skip_crc = true
log_format = "text"
metrics_port = 0
[wal_sync]
mode = "never"
[cluster]
node_id = 0
peers = "$peers"
replication_factor = 2
EOF
}

run_cluster_mode() {
    local variant=$1 mode_v=$2 workers=$3 mode=$4
    local conns; conns=$(conns_for_mode "$mode")
    local Q1 Q2 Q3 C1 C2 C3
    Q1=$(free_port_clean); Q2=$(free_port_clean); Q3=$(free_port_clean)
    C1=$(free_port_clean); C2=$(free_port_clean); C3=$(free_port_clean)
    local PEERS="1=127.0.0.1:$C1,2=127.0.0.1:$C2,3=127.0.0.1:$C3"
    local conf="$CONF_DIR/cluster-$RUN_ID-$variant-$mode.conf"
    write_cluster_conf "$conf" "$mode_v" "$workers" "$PEERS"

    local CPIDS=()
    for N in 1 2 3; do
        case $N in 1) PORT=$Q1;; 2) PORT=$Q2;; 3) PORT=$Q3;; esac
        $SRV --config "$conf" --cluster-node-id "$N" --port "$PORT" \
            > "$CONF_DIR/cl-$RUN_ID-$variant-$mode-$N.log" 2>&1 &
        CPIDS+=($!)
    done
    local READY=0
    for PORT in $Q1 $Q2 $Q3; do
        wait_ready "$PORT" && READY=$((READY+1))
    done
    if [ "$READY" -ne 3 ]; then
        printf "  %-14s conns=%-2d  %s\n" "$mode" "$conns" "FAIL(cluster $READY/3)"
        RESULTS+=("$variant|$mode|FAIL(cluster)")
        for p in "${CPIDS[@]}"; do stop_pid "$p"; done
        return
    fi
    local res; res=$(run_mode "$variant" "$mode" "127.0.0.1:$Q1" "$conns" 5)
    printf "  %-14s conns=%-2d  %s\n" "$mode" "$conns" "$res"
    RESULTS+=("$variant|$mode|$res")
    for p in "${CPIDS[@]}"; do stop_pid "$p"; done
}

# ── Main ─────────────────────────────────────────────────────────

echo "═══════════════════════════════════════════════════════════════"
echo "  bench-harness × vireon.conf matrix (run_id=$RUN_ID)"
echo "  Fresh server per mode — no zombie-connection carryover"
echo "═══════════════════════════════════════════════════════════════"

echo
echo "▶ [1/4] single.conf  (mode=single, workers=1)"
for m in "${SINGLE_MODES[@]}"; do
    run_single_mode "single" "$CONF_DIR/single.conf" "$m"
done

echo
echo "▶ [2/4] multi.conf   (mode=multi, workers=4)"
for m in "${MULTI_MODES[@]}"; do
    run_single_mode "multi" "$CONF_DIR/multi.conf" "$m"
done

echo
echo "▶ [3/4] single-cluster.conf  (single + 3-node cluster, RF=2)"
for m in "${SINGLE_MODES[@]}"; do
    run_cluster_mode "sc" "single" 1 "$m"
done

echo
echo "▶ [4/4] multi-cluster.conf   (multi 2w + 3-node cluster, RF=2)"
for m in "${MULTI_MODES[@]}"; do
    run_cluster_mode "mc" "multi" 2 "$m"
done

# ── Cross-node fan-out correctness (SDK example) ────────────────
# s18 spawns its own 3-node cluster and verifies that subscribers on
# ALL nodes receive every published message (no gaps, no dups).
echo
echo "▶ [5/4] s18 cross-node fan-out correctness (RF=1,2,3 × single,multi)"
for rf in 1 2 3; do
    for mode_v in single multi; do
        s18_label="${mode_v}-rf${rf}"
        s18_log="$CONF_DIR/bench-${RUN_ID}-s18-${s18_label}.log"
        VIREON_CLUSTER_MODE="$mode_v" VIREON_CLUSTER_WORKERS=2 \
            VIREON_CLUSTER_REPLICATION="$rf" \
            timeout 60 "$ROOT/target/x86_64-unknown-linux-gnu/release/examples/s18_cross_node_fanout" \
            > "$s18_log" 2>&1
        s18_rc=$?
        s18_ver=$(grep -oE '(VERIFIED|FAILED)' "$s18_log" | tail -1)
        s18_pub=$(grep -oP '\[publisher\].*?\(\K[0-9.]+ MiB/s' "$s18_log" 2>/dev/null | tail -1)
        s18_del=$(grep -oP '\[delivery\].*?\(\K[0-9.]+ MiB/s' "$s18_log" 2>/dev/null | tail -1)
        if [ "$s18_rc" -eq 0 ] && [[ "$s18_ver" == "VERIFIED" ]]; then
            printf "  %-20s %s\n" "$s18_label" "PASS | pub ${s18_pub:-?} | recv ${s18_del:-?}"
            RESULTS+=("s18|$s18_label|PASS")
        else
            s18_nd=$(grep -E '^\s+node [0-9]:' "$s18_log" | tr '\n' ' ')
            printf "  %-20s %s\n" "$s18_label" "FAIL(rc=$s18_rc) | ${s18_nd}"
            RESULTS+=("s18|$s18_label|FAIL")
        fi
    done
done

# ── Connection-migration smoke test (config flag + /metrics) ────
# Same regression / wiring check as run-matrix.sh, but driven through
# the bench harness stream mode so we exercise the data-plane path.
# Real IP-change simulation requires raw-packet injection in the SDK
# (not yet exposed); this smoke verifies:
#   1. `[quic] migration = true` runs without startup regression.
#   2. `[quic] migration = false` runs (flag parses both ways).
#   3. `/metrics` exposes `vireon_migrations_total` after a workload.
echo
echo "▶ [6/4] connection-migration smoke (stream bench + /metrics wiring)"

# write_migration_conf FILE MIGRATION_FLAG METRICS_PORT
write_migration_conf() {
    local file=$1 flag=$2 mport=$3
    cat > "$file" <<EOF
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "single"
workers = 1
skip_crc = true
log_format = "text"
metrics_port = $mport

[quic]
migration = $flag

[wal_sync]
mode = "never"
EOF
}

wait_metrics_ready() {
    local port=$1
    for _ in $(seq 1 50); do
        if curl -sf "http://127.0.0.1:$port/metrics" >/dev/null 2>&1; then
            return 0
        fi
        sleep 0.2
    done
    return 1
}

# Extract a numeric metric value from /metrics by name.
# metric_value PORT NAME -> echoes the value (or 0 if absent).
metric_value() {
    local port=$1 name=$2
    curl -sf "http://127.0.0.1:$port/metrics" 2>/dev/null \
        | grep -oE "^${name}[[:space:]]+[0-9]+" \
        | awk '{print $2}' | head -1
}

# Bench workload duration in seconds (matches --duration below).
MIG_BENCH_DUR=3

# run_migration_case MIGRATION_FLAG LABEL
run_migration_case() {
    local flag=$1 label=$2
    local sport; sport=$(free_port_clean)
    local mport; mport=$(free_port_clean)
    local conf="$CONF_DIR/bench-migration-$RUN_ID-$label.conf"
    write_migration_conf "$conf" "$flag" "$mport"

    local log="$CONF_DIR/bench-migration-$RUN_ID-$label.log"
    $SRV --config "$conf" --port "$sport" > "$log" 2>&1 &
    local pid=$!
    if ! wait_ready "$sport"; then
        printf "  %-22s %s\n" "$label" "FAIL(server didn't bind $sport)"
        RESULTS+=("migration|$label|FAIL(server)")
        stop_pid "$pid" 2>/dev/null
        return
    fi
    if ! wait_metrics_ready "$mport"; then
        printf "  %-22s %s\n" "$label" "FAIL(/metrics didn't come up on $mport)"
        RESULTS+=("migration|$label|FAIL(metrics)")
        stop_pid "$pid"
        return
    fi

    local mlog="$CONF_DIR/bench-migration-$RUN_ID-$label.stream.log"
    local start=$(date +%s.%N)
    $LOADTEST --target "127.0.0.1:$sport" --mode stream --conns 1 --duration "$MIG_BENCH_DUR" \
        > "$mlog" 2>&1
    local rc=$?
    local end=$(date +%s.%N)
    local elapsed=$(awk "BEGIN{printf \"%.1f\", $end-$start}")

    if [ $rc -ne 0 ]; then
        printf "  %-22s %s\n" "$label" "FAIL(bench rc=$rc) ${elapsed}s"
        RESULTS+=("migration|$label|FAIL(bench)")
        stop_pid "$pid"
        return
    fi

    # Client-side throughput from loadtest output (frames/sec + total MiB).
    local fps mib_total mibs
    fps=$(grep -oP '^frames/sec:\s+\K[0-9.]+' "$mlog" 2>/dev/null | head -1)
    mib_total=$(grep -oP '^bytes:\s+\K[0-9.]+' "$mlog" 2>/dev/null | head -1)
    if [ -n "$mib_total" ]; then
        mibs=$(awk "BEGIN{printf \"%.0f\", $mib_total/$MIG_BENCH_DUR}")
    fi

    # Server-side counters + migration counter from /metrics.
    local mig_count pubs deliv
    mig_count=$(metric_value "$mport" vireon_migrations_total)
    pubs=$(metric_value "$mport" vireon_publishes_total)
    deliv=$(metric_value "$mport" vireon_deliveries_total)
    mig_count=${mig_count:-0}
    pubs=${pubs:-0}
    deliv=${deliv:-0}

    local body; body=$(curl -sf "http://127.0.0.1:$mport/metrics" 2>/dev/null)
    stop_pid "$pid"
    if [ -z "$body" ]; then
        printf "  %-22s %s\n" "$label" "FAIL(/metrics empty) ${elapsed}s"
        RESULTS+=("migration|$label|FAIL(metrics scrape)")
        return
    fi
    if ! echo "$body" | grep -q 'vireon_migrations_total'; then
        printf "  %-22s %s\n" "$label" "FAIL(vireon_migrations_total missing) ${elapsed}s"
        RESULTS+=("migration|$label|FAIL(metric missing)")
        return
    fi

    printf "  %-22s PASS %ss | pub %s MiB/s | %s fps | pubs=%s deliv=%s | vireon_migrations_total=%s\n" \
        "$label" "$elapsed" "${mibs:-?}" "${fps:-?}" "$pubs" "$deliv" "$mig_count"
    RESULTS+=("migration|$label|PASS")
    sleep 1
}

run_migration_case "true"  "migration-on"
run_migration_case "false" "migration-off"

# ── SDK-driven migration (actual Client::migrate() call) ─────────
# The smoke cases above verify config parsing + metric presence with
# a bench workload. This case verifies vireon_migrations_total actually
# INCREMENTS when the SDK triggers a real connection migration.
echo
echo "▶ [6/4b] SDK migration (s19 — actual UDP rebind via Client::migrate)"

run_sdk_migration() {
    local sport; sport=$(free_port_clean)
    local mport; mport=$(free_port_clean)
    local conf="$CONF_DIR/bench-migration-$RUN_ID-sdk.conf"
    write_migration_conf "$conf" "true" "$mport"

    local log="$CONF_DIR/bench-migration-$RUN_ID-sdk.log"
    $SRV --config "$conf" --port "$sport" > "$log" 2>&1 &
    local pid=$!
    if ! wait_ready "$sport"; then
        printf "  %-22s %s\n" "sdk-migration" "FAIL(server didn't bind $sport)"
        RESULTS+=("migration|sdk|FAIL(server)")
        stop_pid "$pid" 2>/dev/null
        return
    fi
    if ! wait_metrics_ready "$mport"; then
        printf "  %-22s %s\n" "sdk-migration" "FAIL(/metrics on $mport)"
        RESULTS+=("migration|sdk|FAIL(metrics)")
        stop_pid "$pid"
        return
    fi

    local mig_before
    mig_before=$(metric_value "$mport" vireon_migrations_total)
    mig_before=${mig_before:-0}

    local slog="$CONF_DIR/bench-migration-$RUN_ID-sdk.workload.log"
    local start=$(date +%s.%N)
    VIREON_ADDR="127.0.0.1:$sport" VIREON_CERT="$CERT" \
        timeout 90 cargo run -p vireon-sdk --release --example s19_connection_migration \
        > "$slog" 2>&1
    local rc=$?
    local end=$(date +%s.%N)
    local elapsed=$(awk "BEGIN{printf \"%.1f\", $end-$start}")

    local mig_after verified
    mig_after=$(metric_value "$mport" vireon_migrations_total)
    mig_after=${mig_after:-0}
    verified=$(grep -cE 'MIGRATION VERIFIED' "$slog" 2>/dev/null || echo 0)

    stop_pid "$pid"

    if [ "$rc" -ne 0 ]; then
        printf "  %-22s FAIL(rc=$rc) %ss\n" "sdk-migration" "$elapsed"
        RESULTS+=("migration|sdk|FAIL(example rc)")
        return
    fi

    local delta=$((mig_after - mig_before))
    if [ "$delta" -gt 0 ] && [ "${verified:-0}" -ge 1 ]; then
        printf "  %-22s PASS %ss | migrations %d->%d (+%d) | VERIFIED\n" \
            "sdk-migration" "$elapsed" "$mig_before" "$mig_after" "$delta"
        RESULTS+=("migration|sdk|PASS")
    else
        printf "  %-22s FAIL %ss | migrations %d->%d (+%d) | verified=%s\n" \
            "sdk-migration" "$elapsed" "$mig_before" "$mig_after" "$delta" "${verified:-0}"
        RESULTS+=("migration|sdk|FAIL(no increment)")
    fi
    sleep 1
}

run_sdk_migration

# ── Summary ─────────────────────────────────────────────────────
echo
echo "═══════════════════════════════════════════════════════════════"
echo "  Summary"
echo "═══════════════════════════════════════════════════════════════"
pass=0; fail=0; skip=0
for r in "${RESULTS[@]}"; do
    if [[ "$r" == *"PASS"* ]]; then
        pass=$((pass+1))
    elif [[ "$r" == *"SKIP"* ]]; then
        skip=$((skip+1))
    else
        fail=$((fail+1))
        echo "  ✗ $r"
    fi
done
echo
echo "  Passed: $pass   Skipped: $skip   Failed: $fail"
echo "═══════════════════════════════════════════════════════════════"
