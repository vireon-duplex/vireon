#!/usr/bin/env bash
# Matrix runner v4 — fresh server per example.
#
# Restarts the server (or cluster) before each example to avoid zombie
# connections from prior examples diluting reactor throughput.
#
# Runtime workspace (logs, generated cluster/migration confs) stays at
# /tmp/vireon-conf-test; certs are read from the repo root so the
# scripts/ directory is self-contained.
#
# Usage:
#   scripts/run-matrix.sh                 # run the full matrix
set -u

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
SRV=$ROOT/target/x86_64-unknown-linux-gnu/release/quic-server
CERT=$ROOT/cert.pem
KEY=$ROOT/key.pem
CONF_DIR=/tmp/vireon-conf-test
RUN_ID=$$

cd "$ROOT" || exit 1

# Kill any lingering server processes to avoid ghost-socket interference.
# Match the binary path specifically so we don't kill our own shell.
pkill -f "$SRV" 2>/dev/null
sleep 3

mkdir -p "$CONF_DIR"

# Sanity: certs must exist.
if [ ! -f "$CERT" ] || [ ! -f "$KEY" ]; then
    echo "ERROR: dev certs missing — expected $CERT and $KEY" >&2
    exit 1
fi

# Auto-generate the base single.conf / multi.conf so the script is
# self-contained (no checked-in conf files needed). Logs + generated
# confs still land in $CONF_DIR.
write_base_confs() {
    cat > "$CONF_DIR/single.conf" <<EOF
# Auto-generated by scripts/run-matrix.sh (run_id=$RUN_ID).
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "single"
workers = 1
skip_crc = true
log_format = "text"
metrics_port = 0

[wal_sync]
mode = "never"
EOF
    cat > "$CONF_DIR/multi.conf" <<EOF
# Auto-generated by scripts/run-matrix.sh (run_id=$RUN_ID).
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "multi"
workers = 4
skip_crc = true
log_format = "text"
metrics_port = 0

[wal_sync]
mode = "never"
EOF
}
write_base_confs

SINGLE_EXAMPLES=(quickstart s07_hol_congestion s11_ordering s12_full_limit s13_aggregate_throughput s14_pool_multiplex s15_consumer_group)
MULTI_EXAMPLES=(quickstart s07_hol_congestion s11_ordering s12_full_limit s13_aggregate_throughput s14_pool_multiplex s15_consumer_group)

RESULTS=()

free_port() {
    python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1",0)); print(s.getsockname()[1]); s.close()'
}

free_port_clean() {
    for _ in $(seq 1 50); do
        local p
        p=$(free_port)
        if ! ss -uln 2>/dev/null | grep -q ":$p "; then
            echo "$p"
            return 0
        fi
    done
    echo "ERROR: no clean port found after 50 tries" >&2
    return 1
}

wait_ready() {
    local port=$1
    for _ in $(seq 1 75); do
        if ss -uln 2>/dev/null | grep -q ":$port "; then
            return 0
        fi
        sleep 0.2
    done
    return 1
}

start_server() {
    local conf=$1 port=$2
    $SRV --config "$conf" --port "$port" > "$CONF_DIR/srv-$RUN_ID-$port.log" 2>&1 &
    local pid=$!
    if ! wait_ready "$port"; then
        echo "FAIL: server didn't bind $port" >&2
        return 1
    fi
    echo "$pid"
}

stop_pid() {
    local pid=$1
    kill -INT "$pid" 2>/dev/null
    for _ in $(seq 1 50); do
        kill -0 "$pid" 2>/dev/null || return 0
        sleep 0.1
    done
    kill -9 "$pid" 2>/dev/null
}

sdk_metric() {
    local log=$1 ex=$2
    case "$ex" in
        quickstart)
            grep -o 'all [0-9]* delivery policies verified' "$log" 2>/dev/null | tail -1
            ;;
        s07_hol_congestion)
            grep 'heaviest stream' "$log" 2>/dev/null | tail -1 \
                | awk '{printf "deliver=%s %s%s p99=%s%s", $5, $6, $7, $10, $11}'
            ;;
        s11_ordering)
            local gaps dup
            gaps=$(grep -oP 'gaps:\s+\K[0-9]+' "$log" 2>/dev/null | tail -1)
            dup=$(grep -oP 'duplicates:\s+\K[0-9]+' "$log" 2>/dev/null | tail -1)
            echo "gaps=${gaps:-?} dup=${dup:-?}"
            ;;
        s12_full_limit)
            local del rate
            del=$(grep -oP 'fan-out delivery:\s+\K[0-9/]+ \([0-9.]+%\)' "$log" 2>/dev/null | tail -1)
            rate=$(grep -oP 'publish rate:\s+\K.*' "$log" 2>/dev/null | tail -1 | sed 's/  */ /g')
            echo "fanout ${del:-?} | ${rate:-?}"
            ;;
        s13_aggregate_throughput)
            local pub del
            pub=$(grep -oP 'publish rate:\s+\K[0-9.]+ GiB/s' "$log" 2>/dev/null | tail -1)
            del=$(grep -oP 'delivery rate:\s+\K[0-9.]+ GiB/s' "$log" 2>/dev/null | tail -1)
            echo "pub ${pub:-?} | recv ${del:-?}"
            ;;
        s14_pool_multiplex)
            grep -oP 'throughput:\s+\K[0-9.]+ MiB/s' "$log" 2>/dev/null | tail -1
            ;;
        s15_consumer_group)
            local del dup bal
            del=$(grep -oP 'delivered:\s+\K[0-9]+' "$log" 2>/dev/null | tail -1)
            dup=$(grep -oP 'duplicates:\s+\K[0-9]+' "$log" 2>/dev/null | tail -1)
            bal=$(grep 'balance:' "$log" 2>/dev/null | tail -1 | sed 's/.*member //')
            echo "delivered ${del:-?} dup ${dup:-?} bal ${bal:-?}"
            ;;
    esac
}

run_example() {
    local variant=$1 ex=$2 addr=$3
    local log="$CONF_DIR/ex-${RUN_ID}-${variant}-${ex}.log"
    local start=$(date +%s.%N)
    VIREON_ADDR="$addr" VIREON_CERT="$CERT" timeout 90 \
        cargo run -p vireon-sdk --release --example "$ex" \
        > "$log" 2>&1
    local rc=$?
    local end=$(date +%s.%N)
    local elapsed=$(awk "BEGIN{printf \"%.1f\", $end-$start}")
    local metric=$(sdk_metric "$log" "$ex")
    if [ $rc -eq 0 ]; then
        echo "PASS ${elapsed}s | ${metric}"
    else
        echo "FAIL(rc=$rc) ${elapsed}s | ${metric}"
    fi
}

# ── Per-example runner helpers (fresh server each time) ──────────

# run_single_example VARIANT CONF EXAMPLE
run_single_example() {
    local variant=$1 conf=$2 ex=$3
    local port; port=$(free_port_clean)
    local pid; pid=$(start_server "$conf" "$port")
    if [ -z "$pid" ]; then
        printf "  %-30s %s\n" "$ex" "FAIL(server start)"
        RESULTS+=("$variant|$ex|FAIL(server)")
        return
    fi
    local res; res=$(run_example "$variant" "$ex" "127.0.0.1:$port")
    printf "  %-30s %s\n" "$ex" "$res"
    RESULTS+=("$variant|$ex|$res")
    stop_pid "$pid"
}

# write_cluster_conf FILE MODE WORKERS PEERS
write_cluster_conf() {
    local file=$1 mode=$2 workers=$3 peers=$4
    cat > "$file" <<EOF
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "$mode"
workers = $workers
skip_crc = true
log_format = "text"
metrics_port = 0
[wal_sync]
mode = "never"
[cluster]
node_id = 0
peers = "$peers"
replication_factor = 2
EOF
}

# run_cluster_example VARIANT MODE WORKERS EXAMPLE
run_cluster_example() {
    local variant=$1 mode=$2 workers=$3 ex=$4
    local Q1 Q2 Q3 C1 C2 C3
    Q1=$(free_port_clean); Q2=$(free_port_clean); Q3=$(free_port_clean)
    C1=$(free_port_clean); C2=$(free_port_clean); C3=$(free_port_clean)
    local PEERS="1=127.0.0.1:$C1,2=127.0.0.1:$C2,3=127.0.0.1:$C3"
    local conf="$CONF_DIR/cluster-$RUN_ID-$variant-$ex.conf"
    write_cluster_conf "$conf" "$mode" "$workers" "$PEERS"

    local CPIDS=()
    for N in 1 2 3; do
        case $N in 1) PORT=$Q1;; 2) PORT=$Q2;; 3) PORT=$Q3;; esac
        $SRV --config "$conf" --cluster-node-id "$N" --port "$PORT" \
            > "$CONF_DIR/cl-$RUN_ID-$variant-$ex-$N.log" 2>&1 &
        CPIDS+=($!)
    done
    local READY=0
    for PORT in $Q1 $Q2 $Q3; do
        wait_ready "$PORT" && READY=$((READY+1))
    done
    if [ "$READY" -ne 3 ]; then
        printf "  %-30s %s\n" "$ex" "FAIL(cluster bind $READY/3)"
        RESULTS+=("$variant|$ex|FAIL(cluster)")
        for p in "${CPIDS[@]}"; do stop_pid "$p"; done
        return
    fi
    local res; res=$(run_example "$variant" "$ex" "127.0.0.1:$Q1")
    printf "  %-30s %s\n" "$ex" "$res"
    RESULTS+=("$variant|$ex|$res")
    for p in "${CPIDS[@]}"; do stop_pid "$p"; done
}

# ── Main ─────────────────────────────────────────────────────────

echo "═══════════════════════════════════════════════════════════════"
echo "  Vireon client-sdk × vireon.conf matrix (run_id=$RUN_ID)"
echo "  Fresh server per example — no zombie-connection carryover"
echo "═══════════════════════════════════════════════════════════════"

echo
echo "▶ [1/4] single.conf  (mode=single, workers=1)"
for ex in "${SINGLE_EXAMPLES[@]}"; do
    run_single_example "single" "$CONF_DIR/single.conf" "$ex"
done

echo
echo "▶ [2/4] multi.conf   (mode=multi, workers=4)"
for ex in "${MULTI_EXAMPLES[@]}"; do
    run_single_example "multi" "$CONF_DIR/multi.conf" "$ex"
done

echo
echo "▶ [3/4] single-cluster.conf  (single + 3-node cluster, RF=2)"
for ex in "${SINGLE_EXAMPLES[@]}"; do
    run_cluster_example "sc" "single" 1 "$ex"
done

echo
echo "▶ [4/4] multi-cluster.conf   (multi 2w + 3-node cluster, RF=2)"
for ex in "${MULTI_EXAMPLES[@]}"; do
    run_cluster_example "mc" "multi" 2 "$ex"
done

# ── Cross-node fan-out correctness (self-contained cluster) ──────
# s18 spawns its own 3-node cluster and verifies that subscribers on
# ALL nodes receive every published message (no gaps, no dups).
echo
echo "▶ [5/4] s18 cross-node fan-out (3-node cluster, self-contained)"
for rf in 1 2 3; do
    for mode_v in single multi; do
        s18_label="${mode_v}-rf${rf}"
        s18_log="$CONF_DIR/ex-${RUN_ID}-s18-${s18_label}.log"
        s18_start=$(date +%s.%N)
        VIREON_CLUSTER_MODE="$mode_v" VIREON_CLUSTER_WORKERS=2 \
            VIREON_CLUSTER_REPLICATION="$rf" \
            timeout 60 cargo run -p vireon-sdk --release --example s18_cross_node_fanout \
            > "$s18_log" 2>&1
        s18_rc=$?
        s18_end=$(date +%s.%N)
        s18_elapsed=$(awk "BEGIN{printf \"%.1f\", $s18_end-$s18_start}")
        s18_ver=$(grep -oE '(VERIFIED|FAILED)' "$s18_log" | tail -1)
        s18_pub=$(grep -oP '\[publisher\].*?\(\K[0-9.]+ MiB/s' "$s18_log" 2>/dev/null | tail -1)
        s18_del=$(grep -oP '\[delivery\].*?\(\K[0-9.]+ MiB/s' "$s18_log" 2>/dev/null | tail -1)
        if [ "$s18_rc" -eq 0 ] && [[ "$s18_ver" == "VERIFIED" ]]; then
            printf "  %-20s %s\n" "$s18_label" "PASS ${s18_elapsed}s | pub ${s18_pub:-?} | recv ${s18_del:-?}"
            RESULTS+=("s18|$s18_label|PASS")
        else
            printf "  %-20s %s\n" "$s18_label" "FAIL(rc=$s18_rc) ${s18_elapsed}s"
            RESULTS+=("s18|$s18_label|FAIL")
        fi
    done
done

# ── Connection-migration smoke test ─────────────────────────────
# We can't simulate a real IP/port change in loopback without raw
# QUIC packet injection in the SDK. But we CAN verify:
#   1. `[quic] migration = true` parses and runs (no regression).
#   2. `[quic] migration = false` parses too (flag honoured).
#   3. `/metrics` exposes `vireon_migrations_total` after workload.
echo
echo "▶ [6/4] connection-migration smoke (config flag + /metrics wiring)"

# write_migration_conf FILE MIGRATION_FLAG METRICS_PORT
write_migration_conf() {
    local file=$1 flag=$2 mport=$3
    cat > "$file" <<EOF
bind = "127.0.0.1"
cert = "$CERT"
key = "$KEY"
mode = "single"
workers = 1
skip_crc = true
log_format = "text"
metrics_port = $mport

[quic]
migration = $flag

[wal_sync]
mode = "never"
EOF
}

wait_metrics_ready() {
    local port=$1
    for _ in $(seq 1 50); do
        if curl -sf "http://127.0.0.1:$port/metrics" >/dev/null 2>&1; then
            return 0
        fi
        sleep 0.2
    done
    return 1
}

# Extract a numeric metric value from /metrics by name.
# metric_value PORT NAME -> echoes the value (or 0 if absent).
metric_value() {
    local port=$1 name=$2
    curl -sf "http://127.0.0.1:$port/metrics" 2>/dev/null \
        | grep -oE "^${name}[[:space:]]+[0-9]+" \
        | awk '{print $2}' | head -1
}

# run_migration_case MIGRATION_FLAG LABEL
run_migration_case() {
    local flag=$1 label=$2
    local sport; sport=$(free_port_clean)
    local mport; mport=$(free_port_clean)
    local conf="$CONF_DIR/migration-$RUN_ID-$label.conf"
    write_migration_conf "$conf" "$flag" "$mport"

    local log="$CONF_DIR/migration-$RUN_ID-$label.log"
    $SRV --config "$conf" --port "$sport" > "$log" 2>&1 &
    local pid=$!
    if ! wait_ready "$sport"; then
        printf "  %-22s %s\n" "$label" "FAIL(server didn't bind $sport)"
        RESULTS+=("migration|$label|FAIL(server)")
        stop_pid "$pid" 2>/dev/null
        return
    fi
    if ! wait_metrics_ready "$mport"; then
        printf "  %-22s %s\n" "$label" "FAIL(/metrics didn't come up on $mport)"
        RESULTS+=("migration|$label|FAIL(metrics)")
        stop_pid "$pid"
        return
    fi

    # Snapshot byte counters BEFORE the workload so we can compute
    # throughput from the delta. quickstart is a correctness workload,
    # not a benchmark — it doesn't print MiB/s itself, so we derive
    # throughput from server-side counters.
    local recv_before sent_before
    recv_before=$(metric_value "$mport" vireon_bytes_recv_total)
    sent_before=$(metric_value "$mport" vireon_bytes_sent_total)
    recv_before=${recv_before:-0}
    sent_before=${sent_before:-0}

    local mlog="$CONF_DIR/migration-$RUN_ID-$label.workload.log"
    local start=$(date +%s.%N)
    VIREON_ADDR="127.0.0.1:$sport" VIREON_CERT="$CERT" \
        timeout 90 cargo run -p vireon-sdk --release --example quickstart \
        > "$mlog" 2>&1
    local rc=$?
    local end=$(date +%s.%N)
    local elapsed=$(awk "BEGIN{printf \"%.3f\", $end-$start}")

    if [ $rc -ne 0 ]; then
        printf "  %-22s %s\n" "$label" "FAIL(workload rc=$rc) ${elapsed}s"
        RESULTS+=("migration|$label|FAIL(workload)")
        stop_pid "$pid"
        return
    fi

    # Snapshot AFTER. Compute MiB/s from delta / elapsed.
    local recv_after sent_after mig_count
    recv_after=$(metric_value "$mport" vireon_bytes_recv_total)
    sent_after=$(metric_value "$mport" vireon_bytes_sent_total)
    mig_count=$(metric_value "$mport" vireon_migrations_total)
    recv_after=${recv_after:-0}
    sent_after=${sent_after:-0}
    mig_count=${mig_count:-0}

    local body; body=$(curl -sf "http://127.0.0.1:$mport/metrics" 2>/dev/null)
    stop_pid "$pid"
    if [ -z "$body" ]; then
        printf "  %-22s %s\n" "$label" "FAIL(/metrics empty) ${elapsed}s"
        RESULTS+=("migration|$label|FAIL(metrics scrape)")
        return
    fi
    if ! echo "$body" | grep -q 'vireon_migrations_total'; then
        printf "  %-22s %s\n" "$label" "FAIL(vireon_migrations_total missing) ${elapsed}s"
        RESULTS+=("migration|$label|FAIL(metric missing)")
        return
    fi

    # Throughput = delta bytes / elapsed. Show MiB/s when ≥ 1, else
    # KiB/s (quickstart sends tiny payloads so MiB/s would round to 0).
    local recv_bps sent_bps recv_rate sent_rate pubs deliv
    recv_bps=$(awk "BEGIN{printf \"%.0f\", ($recv_after - $recv_before) / $elapsed}")
    sent_bps=$(awk "BEGIN{printf \"%.0f\", ($sent_after - $sent_before) / $elapsed}")
    if [ "$recv_bps" -ge 1048576 ]; then
        recv_rate=$(awk "BEGIN{printf \"%.1f MiB/s\", $recv_bps/1048576}")
    else
        recv_rate=$(awk "BEGIN{printf \"%.1f KiB/s\", $recv_bps/1024}")
    fi
    if [ "$sent_bps" -ge 1048576 ]; then
        sent_rate=$(awk "BEGIN{printf \"%.1f MiB/s\", $sent_bps/1048576}")
    else
        sent_rate=$(awk "BEGIN{printf \"%.1f KiB/s\", $sent_bps/1024}")
    fi
    pubs=$(metric_value "$mport" vireon_publishes_total)
    deliv=$(metric_value "$mport" vireon_deliveries_total)
    pubs=${pubs:-0}
    deliv=${deliv:-0}

    printf "  %-22s PASS %ss | pub %s | recv %s | pubs=%s deliv=%s | vireon_migrations_total=%s\n" \
        "$label" "$elapsed" "$recv_rate" "$sent_rate" "$pubs" "$deliv" "$mig_count"
    RESULTS+=("migration|$label|PASS")
    sleep 1
}

run_migration_case "true"  "migration-on"
run_migration_case "false" "migration-off"

# ── SDK-driven migration (actual Client::migrate() call) ─────────
# The smoke cases above verify config parsing + metric presence.
# This case verifies vireon_migrations_total actually INCREMENTS
# when the SDK triggers a real connection migration via Client::migrate().
echo
echo "▶ [6/4b] SDK migration (s19 — actual UDP rebind via Client::migrate)"

run_sdk_migration() {
    local sport; sport=$(free_port_clean)
    local mport; mport=$(free_port_clean)
    local conf="$CONF_DIR/migration-$RUN_ID-sdk.conf"
    write_migration_conf "$conf" "true" "$mport"

    local log="$CONF_DIR/migration-$RUN_ID-sdk.log"
    $SRV --config "$conf" --port "$sport" > "$log" 2>&1 &
    local pid=$!
    if ! wait_ready "$sport"; then
        printf "  %-22s %s\n" "sdk-migration" "FAIL(server didn't bind $sport)"
        RESULTS+=("migration|sdk|FAIL(server)")
        stop_pid "$pid" 2>/dev/null
        return
    fi
    if ! wait_metrics_ready "$mport"; then
        printf "  %-22s %s\n" "sdk-migration" "FAIL(/metrics on $mport)"
        RESULTS+=("migration|sdk|FAIL(metrics)")
        stop_pid "$pid"
        return
    fi

    local mig_before
    mig_before=$(metric_value "$mport" vireon_migrations_total)
    mig_before=${mig_before:-0}

    local slog="$CONF_DIR/migration-$RUN_ID-sdk.workload.log"
    local start=$(date +%s.%N)
    VIREON_ADDR="127.0.0.1:$sport" VIREON_CERT="$CERT" \
        timeout 90 cargo run -p vireon-sdk --release --example s19_connection_migration \
        > "$slog" 2>&1
    local rc=$?
    local end=$(date +%s.%N)
    local elapsed=$(awk "BEGIN{printf \"%.1f\", $end-$start}")

    local mig_after verified
    mig_after=$(metric_value "$mport" vireon_migrations_total)
    mig_after=${mig_after:-0}
    verified=$(grep -cE 'MIGRATION VERIFIED' "$slog" 2>/dev/null || echo 0)

    stop_pid "$pid"

    if [ "$rc" -ne 0 ]; then
        printf "  %-22s FAIL(rc=$rc) %ss\n" "sdk-migration" "$elapsed"
        RESULTS+=("migration|sdk|FAIL(example rc)")
        return
    fi

    local delta=$((mig_after - mig_before))
    if [ "$delta" -gt 0 ] && [ "${verified:-0}" -ge 1 ]; then
        printf "  %-22s PASS %ss | migrations %d->%d (+%d) | VERIFIED\n" \
            "sdk-migration" "$elapsed" "$mig_before" "$mig_after" "$delta"
        RESULTS+=("migration|sdk|PASS")
    else
        printf "  %-22s FAIL %ss | migrations %d->%d (+%d) | verified=%s\n" \
            "sdk-migration" "$elapsed" "$mig_before" "$mig_after" "$delta" "${verified:-0}"
        RESULTS+=("migration|sdk|FAIL(no increment)")
    fi
    sleep 1
}

run_sdk_migration

# Summary
echo
echo "═══════════════════════════════════════════════════════════════"
echo "  Summary"
echo "═══════════════════════════════════════════════════════════════"
pass=0; fail=0; skip=0
for r in "${RESULTS[@]}"; do
    if [[ "$r" == *"PASS"* ]]; then
        pass=$((pass+1))
    elif [[ "$r" == *"SKIP"* ]]; then
        skip=$((skip+1))
    else
        fail=$((fail+1))
        echo "  ✗ $r"
    fi
done
echo
echo "  Passed: $pass   Skipped: $skip   Failed: $fail"
echo "═══════════════════════════════════════════════════════════════"
